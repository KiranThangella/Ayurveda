/**
 * Full Ayurveda Knowledge Curriculum
 * ------------------------------------
 * Goal: every classical branch of Ayurveda (Ashtanga Ayurveda) is represented,
 * so that across all books on the platform, "ఆయుర్వేదం antha ikkade undi"
 * (all of Ayurveda is here) actually holds true — nothing structurally missing.
 *
 * Structure: 8 series (knowledge domains) x ~5 topics each = 40 topics.
 * Each topic carries a `mustCover` list — the specific sub-concepts the AI
 * generator is REQUIRED to distribute across chapters. This is what prevents
 * "missing a point" — the outline prompt is built directly from this list.
 */

export interface CurriculumTopic {
  id: string;
  series: string;
  titleEn: string;
  titleTe: string;
  /** One-paragraph scope note — keeps the AI from wandering into another topic's territory */
  scopeEn: string;
  scopeTe: string;
  /** Specific sub-concepts that MUST appear somewhere in the book. This is the anti-gap list. */
  mustCover: string[];
  /** Classical source texts to ground the content in (not to quote verbatim, only to reference) */
  classicalSources: string[];
  /** Recommended depth for a book that actually does the topic justice */
  recommendedChapters: number;
  difficulty: 'foundation' | 'intermediate' | 'advanced';
  /** Pregnancy, children, mental-health, or therapeutic-Panchakarma content —
   *  AI output for these topics must be held for human review before it goes
   *  public, regardless of generation_status otherwise reaching 'complete'. */
  requiresReview?: boolean;
}

export interface CurriculumSeries {
  id: string;
  nameEn: string;
  nameTe: string;
  descriptionEn: string;
  descriptionTe: string;
  order: number;
}

